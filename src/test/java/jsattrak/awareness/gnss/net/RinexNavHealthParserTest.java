    @Test
    void parsesRinex3GzippedHealthAcrossAllFourConstellationsAndTruncatedTail() throws Exception {
        byte[] gz = gzip(RINEX3_FIXTURE);
        RinexNavHealthParser.ParseResult res = RinexNavHealthParser.parse(new ByteArrayInputStream(gz));
        assertTrue(res.latestByPrn().get("G01").healthy());
        assertFalse(res.latestByPrn().get("G07").healthy());
        assertTrue(res.latestByPrn().get("E11").healthy());
        assertFalse(res.latestByPrn().get("E18").healthy());
        assertFalse(res.latestByPrn().get("R05").healthy());
        assertTrue(res.latestByPrn().get("C19").healthy());
        assertFalse(res.latestByPrn().get("C33").healthy());
        assertNull(res.latestByPrn().get("J01"));
        assertNull(res.latestByPrn().get("G12")); // truncated tail ignored cleanly
    }

    @Test
    void parsesRinex4RecordsAndSkipsStoIonEopBlocks() throws Exception {
        RinexNavHealthParser.ParseResult res = RinexNavHealthParser.parse(
                new ByteArrayInputStream(RINEX4_FIXTURE.getBytes(StandardCharsets.UTF_8)));
        assertTrue(res.latestByPrn().get("G01").healthy());
        assertFalse(res.latestByPrn().get("C21").healthy()); // CNV1 HS != 0
        assertTrue(res.rinexVersion().startsWith("4"));
    }

    static byte[] gzip(String text) throws Exception {
        ByteArrayOutputStream baos = new ByteArrayOutputStream();
        try (GZIPOutputStream gz = new GZIPOutputStream(baos)) {
            gz.write(text.getBytes(StandardCharsets.UTF_8));
        }
        return baos.toByteArray();
    }
